"""The six broken BIFs a user reported: 1–63 frames instead of the ~770 a two-hour film needs.

They were generated by runs that died just after the opening, and the old audit skipped them because it could not
read the .strm's runtime that day. With a stored runtime (or a probe that retries), every one must be reported.
"""

from __future__ import annotations

import struct
from pathlib import Path

import pytest

from media_preview_generator.bif_reader import BIF_MAGIC
from media_preview_generator.previews_audit import check_preview

#: frame counts of the six real files the user sent (Caribbean …, FC2 …)
FRAME_COUNTS = [2, 7, 1, 1, 63, 1]
RUNTIME_S = 7695.712  # RunTimeTicks 76957120000 from <name>-mediainfo.json, = ffprobe on the .strm URL


def _write_bif(path: Path, frames: int) -> Path:
    payload = b"\xff\xd8\xff\xd9"
    body = payload * frames
    first = 64 + (frames + 1) * 8
    index = bytearray()
    for number in range(frames):
        index += struct.pack("<II", number, first + number * len(payload))
    index += struct.pack("<II", 0xFFFFFFFF, first + len(body))
    header = bytearray(BIF_MAGIC) + struct.pack("<III", 0, frames, 10_000)
    header += b"\x00" * (64 - len(header))
    path.write_bytes(bytes(header) + bytes(index) + body)
    return path


@pytest.mark.parametrize("frames", FRAME_COUNTS)
def test_a_truncated_preview_is_reported_with_a_known_runtime(tmp_path, frames):
    media = tmp_path / "film.strm"
    media.write_text("http://share.invalid/x", encoding="utf-8")
    preview = _write_bif(tmp_path / "film-320-10.bif", frames)

    problem = check_preview(str(media), str(preview), runtime_s=RUNTIME_S)

    assert problem is not None, f"{frames} frames of a 128-minute film must not pass"
    assert problem.frames == frames


@pytest.mark.parametrize("frames", FRAME_COUNTS)
def test_a_truncated_preview_is_reported_even_when_the_link_is_dead(tmp_path, monkeypatch, frames):
    """No json, no probe answer: a preview covering only the opening is still recognisably wrong."""
    monkeypatch.setattr(
        "media_preview_generator.previews_audit._runtime_seconds", lambda _path: None
    )
    media = tmp_path / "film.strm"
    media.write_text("http://share.invalid/x", encoding="utf-8")
    preview = _write_bif(tmp_path / "film-320-10.bif", frames)

    problem = check_preview(str(media), str(preview))

    assert problem is not None, f"{frames} frames must not hide behind an unreadable link"

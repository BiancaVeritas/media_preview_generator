#!/usr/bin/env python3
"""Build the Chinese UI catalogue from the tracked JSON into the two files the app reads.

``i18n/zh-CN.json`` is the source of truth and is edited by hand::

    {"strings":  {"Save": "保存", ...},          # a whole label, matched exactly
     "patterns": [["Retry {0}/{1}", "重试 {0}/{1}"], ...]}   # a sentence with live values

``i18n/overrides.json`` holds corrections and additions layered on top; it is
merged into the JSON the first time and then kept only as documentation of what
was fixed by hand.

Two outputs:

* ``media_preview_generator/web/i18n/zh-CN.json`` — read on the server, so a page
  arrives already in Chinese (``web/server_i18n.py``).
* ``media_preview_generator/web/static/i18n/zh-CN.js`` — loaded by the browser for
  the text the app writes after the page loads (``static/js/i18n.js``).

Usage::

    python scripts/build_i18n_catalogue.py
    python scripts/build_i18n_catalogue.py --check   # fail when an output is stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "i18n" / "zh-CN.json"
OVERRIDES = ROOT / "i18n" / "overrides.json"
SERVER_OUT = ROOT / "media_preview_generator" / "web" / "i18n" / "zh-CN.json"
BROWSER_OUT = ROOT / "media_preview_generator" / "web" / "static" / "i18n" / "zh-CN.js"

_SLOT_RE = re.compile(r"\{(\d+)\}")


def _load_source() -> dict:
    rows = json.loads(SOURCE.read_text(encoding="utf-8"))
    strings = {str(k): str(v) for k, v in (rows.get("strings") or {}).items() if str(v).strip()}
    patterns = {tuple(pair) for pair in rows.get("patterns") or [] if len(pair) == 2 and pair[1].strip()}
    if OVERRIDES.exists():
        over = json.loads(OVERRIDES.read_text(encoding="utf-8"))
        for key, value in (over.get("strings") or {}).items():
            if str(value).strip():
                strings[key] = str(value)
        for pair in over.get("patterns") or []:
            if len(pair) == 2 and pair[1].strip():
                patterns.add((pair[0], pair[1]))
    # Longest templates first: "Add {0} server" must win over "Add {0}".
    ordered = [list(pair) for pair in sorted(patterns, key=lambda pair: -len(pair[0]))]
    return {"strings": dict(sorted(strings.items())), "patterns": ordered}


def _check_patterns(patterns: list[list[str]]) -> list[str]:
    """Templates that changed their placeholders, which would break the substitution."""
    bad = []
    for source, target in patterns:
        if sorted(_SLOT_RE.findall(source)) != sorted(_SLOT_RE.findall(target)):
            bad.append(f"{source} -> {target}")
    return bad


def _browser_script(catalogue: dict) -> str:
    return "\n".join(
        [
            "/* Generated by scripts/build_i18n_catalogue.py from i18n/zh-CN.json -- do not edit by hand.",
            " * Chinese UI strings keyed by the English text they replace, for static/js/i18n.js. */",
            "window.__MPG_I18N__ = window.__MPG_I18N__ || {};",
            'window.__MPG_I18N__["zh-CN"] = '
            + json.dumps(catalogue["strings"], ensure_ascii=False, indent=1, sort_keys=True)
            + ";",
            "window.__MPG_I18N_PATTERNS__ = window.__MPG_I18N_PATTERNS__ || {};",
            'window.__MPG_I18N_PATTERNS__["zh-CN"] = '
            + json.dumps(catalogue["patterns"], ensure_ascii=False, indent=1)
            + ";",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when an output is missing or out of date")
    args = parser.parse_args()

    if not SOURCE.exists():
        print(f"missing {SOURCE.relative_to(ROOT)}", file=sys.stderr)
        return 1
    catalogue = _load_source()
    bad = _check_patterns(catalogue["patterns"])
    if bad:
        print(f"{len(bad)} template(s) changed their placeholders:", file=sys.stderr)
        for row in bad[:20]:
            print(f"  {row}", file=sys.stderr)

    server_payload = json.dumps(catalogue, ensure_ascii=False, indent=1, sort_keys=True) + "\n"
    browser_payload = _browser_script(catalogue)
    outputs = {SERVER_OUT: server_payload, BROWSER_OUT: browser_payload}

    if args.check:
        stale = [path for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        if stale or bad:
            for path in stale:
                print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("catalogue outputs are up to date")
        return 0

    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(
        f"{len(catalogue['strings'])} labels + {len(catalogue['patterns'])} sentence patterns "
        f"-> {SERVER_OUT.relative_to(ROOT)} and {BROWSER_OUT.relative_to(ROOT)}"
    )
    return 0 if not bad else 1


if __name__ == "__main__":
    raise SystemExit(main())
